// Embeds templates/*.md into src/templates.generated.ts. The engine is pure (no filesystem, ARCHITECTURE.md
// rule 4), so it carries the template text in code; test/templates.test.ts fails if the two drift.
// Run: npm run templates -w @waronsaas/context-engine
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "templates");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".md"))
  .sort();
const entries = files.map((f) => `  ${JSON.stringify(f.slice(0, -3))}: ${JSON.stringify(readFileSync(join(dir, f), "utf8"))},`);
const out = `// GENERATED by scripts/embed-templates.mjs from templates/*.md. Do not edit by hand.\nexport const TEMPLATE_SOURCES: Readonly<Record<string, string>> = {\n${entries.join("\n")}\n};\n`;
writeFileSync(join(root, "src", "templates.generated.ts"), out);
console.log(`embedded ${files.length} templates`);
